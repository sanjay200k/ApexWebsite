import assert from 'node:assert/strict';
import {writeTrackerValue,sleepDebt,normalizeValue} from '../js/trackers.js';
import {renderTrendChart} from '../js/charts.js';
import {mergeStates} from '../js/state.js';
const st={trackerLogs:{},settings:{}};
const rating={id:'r',type:'rating',direction:'higher',dailyGoal:5};
writeTrackerValue(st,rating,'2026-01-01',4); writeTrackerValue(st,rating,'2026-01-01',0);
assert.equal(Object.keys(st.trackerLogs).length,0);
assert.throws(()=>writeTrackerValue(st,rating,'2026-01-01',9));
const s={trackerLogs:{'sleep|2026-01-02':{trackerId:'sleep',date:'2026-01-02',value:6}},settings:{}};
assert.equal(sleepDebt(s,{id:'sleep'},['2026-01-01','2026-01-02']),2);
const lo={id:'x',direction:'lower',dailyGoal:10}; const hi={id:'y',direction:'higher',dailyGoal:10};
assert.ok(normalizeValue({settings:{}},lo,5)>normalizeValue({settings:{}},lo,20));
assert.ok(normalizeValue({settings:{}},hi,20)>normalizeValue({settings:{}},hi,5));
const html=renderTrendChart({series:[{name:'a',color:'#7ea6ff',points:[{date:'2026-01-01',value:3},{date:'2026-01-02',value:0},{date:'2026-01-03',value:4},{date:'2026-01-04',value:5}]}]});
assert.equal((html.match(/class="tracker-area" d="([^"]*)"/)[1].match(/M/g)||[]).length,2);
const m=mergeStates({lastModified:'2',logs:{a:{v:1}},goals:[{id:'g1'}]},{lastModified:'1',logs:{b:{v:2}},goals:[{id:'g2'}]});
assert.deepEqual(Object.keys(m.logs).sort(),['a','b']); assert.equal(m.goals.length,2);
console.log('fixes ok');
